#!/usr/bin/env -S zsh -f
# Lowercase zsh special parameters, across every loadable module, as a Lua set.
setopt err_exit extended_glob

# Specials of modules this machine does not build (zsh/db/gdbm on macOS).
EXTRA=(zgdbm_tied)

zmodload zsh/parameter
local dir so mod
local -a mods
for dir in $module_path; do
    for so in $dir/zsh/**/*.so(N); do
        mod=${${so#$dir/}%.so}
        [[ $mod == zsh/(example|newuser) ]] || mods+=($mod)
    done
done
(( $#mods )) || { print -u2 "no zsh modules under: $module_path"; exit 1 }
for mod in $mods; do
    zmodload $mod || { print -u2 "failed to load $mod"; exit 1 }
done

local -a names=(${(k)parameters[(R)*special*]:#^[a-z_]*} $EXTRA)
print -- '-- Generated by zsh_special_params.lua.sh; do not edit.'
print -- "-- zsh $ZSH_VERSION, $OSTYPE"
print -- 'return {'
print -lr -- '    ["'${^${(ou)names}}'"] = true,'
print -- '}'
